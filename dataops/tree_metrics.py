DEFAULT_SAMPLE_BATCH = "/Users/siddharthsabata/dev/research/sistem-transform/dataset/combined_experiments.pkl"


def analyse_tree_dicts(tree_dicts: Sequence[Mapping[str, Any]], bins: str | int = "auto") -> Dict[str, Any]:
    """Run the full analysis pipeline on an in-memory list of tree dictionaries."""

    metrics = [compute_tree_metrics(tree) for tree in tree_dicts]
    averages = aggregate_metrics(metrics)
    series = metric_series(metrics)
    figures = create_histograms(series, bins=bins) if metrics else {}
    validity = validity_summary(metrics)

    return {
        "metrics": metrics,
        "averages": averages,
        "histograms": figures,
        "validity": validity,
    }


def run_sample_analysis(batch_path: str = DEFAULT_SAMPLE_BATCH, bins: str | int = "auto") -> Dict[str, Any]:
    """Load a pickle batch, analyse it, and print a short textual summary."""

    with open(batch_path, "rb") as handle:
        tree_dicts = pickle.load(handle)

    analysis = analyse_tree_dicts(tree_dicts, bins=bins)

    averages = analysis["averages"]
    validity = analysis["validity"]

    print("Average metrics:")
    for key, value in averages.items():
        print(f"  {key}: {value:.2f}")

    print("\nValidity summary:")
    print(f"  Passed: {validity['passed']}")
    print(f"  Failed: {validity['failed']}")
    print(f"  Pass percentage: {validity['pass_percentage']:.2f}%")

    return analysis



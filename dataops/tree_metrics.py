"""tree_metrics.py
====================

Utility helpers to study batches of mutation graphs generated by
``phylogeny_list.PhylogenyList``.  Each tree dictionary exposes ``tree_id``,
``X`` (node types), ``E`` (adjacency matrix of edge types), and ``L`` (labels).

This module focuses on three tasks:

* Compute per-tree summary metrics and aggregate means across a batch.
* Visualise the distributions of those metrics via Matplotlib histograms.
* Validate that each graph obeys our mutation-graph rules and report a
  pass-rate percentage.

Usage example (runs the bundled sample batch and prints a report):

    >>> from tree_metrics import run_sample_analysis
    >>> analysis = run_sample_analysis()
    Average metrics:
      average_total_nodes: ...
      ...
    Validity summary:
      Passed: ...
      Failed: ...
      Pass percentage: ...

The code prefers clarity over cleverness and keeps the logic modular so that
callers can mix-and-match the helpers when running analyses or notebooks.
"""

from __future__ import annotations

import pickle
from dataclasses import dataclass
from typing import Any, Dict, Iterable, List, Mapping, MutableMapping, Optional, Sequence, Tuple

import matplotlib.pyplot as plt
import numpy as np


# ---------------------------------------------------------------------------
# Data containers
# ---------------------------------------------------------------------------


@dataclass
class ValidityResult:
    """Hold the outcome of the mutation-graph validity checks.

    Attributes:
        is_valid: ``True`` when every rule passes.
        has_cycle: ``True`` if the clone-only subgraph contains a cycle.
        root_has_single_clone_neighbor: ``True`` when the root has exactly one
            clone neighbour connected via a clone edge.
        clone_edge_types_valid: ``True`` when clone edges (type ``1``) only
            connect root/clone nodes.
        mutation_edge_types_valid: ``True`` when mutation edges (type ``2``)
            only connect clone nodes to mutation nodes.
    """

    is_valid: bool
    has_cycle: bool
    root_has_single_clone_neighbor: bool
    clone_edge_types_valid: bool
    mutation_edge_types_valid: bool


@dataclass
class TreeMetrics:
    """Per-tree statistics derived from the adjacency matrix and node types."""

    tree_id: str
    total_nodes: int
    root_nodes: int
    clone_nodes: int
    mutation_nodes: int
    total_edges: int
    clone_edges: int
    mutation_edges: int
    validity: ValidityResult


# ---------------------------------------------------------------------------
# Core metric helpers
# ---------------------------------------------------------------------------


def _to_numpy(tree_dict: Mapping[str, Any]) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Convert raw ``list`` storage back into ``numpy`` arrays.

    The pickle files we consume keep built-in Python containers for
    compatibility, so we normalise them here for downstream vectorised logic.
    """

    node_types = np.asarray(tree_dict["X"], dtype=int)
    adjacency = np.asarray(tree_dict["E"], dtype=int)
    labels = np.asarray(tree_dict.get("L", []), dtype=object)
    return node_types, adjacency, labels


def _count_edges(adjacency: np.ndarray) -> Tuple[int, int, int]:
    """Count total, clone, and mutation edges using the upper-triangle only."""

    # We treat clone and mutation edges as undirected, therefore the adjacency
    # matrix is symmetric.  Counting only the upper triangle avoids double
    # counting while respecting the input contract.
    upper_r, upper_c = np.triu_indices_from(adjacency, k=1)
    upper_values = adjacency[upper_r, upper_c]

    total_edges = int(np.count_nonzero(upper_values))
    clone_edges = int(np.count_nonzero(upper_values == 1))
    mutation_edges = int(np.count_nonzero(upper_values == 2))
    return total_edges, clone_edges, mutation_edges


def _clone_neighbors(adjacency: np.ndarray, node_types: np.ndarray, node_index: int) -> np.ndarray:
    """Return neighbour indices connected via clone edges (type ``1``)."""

    clone_mask = adjacency[node_index] == 1
    neighbours = np.flatnonzero(clone_mask)
    return neighbours


def _has_clone_cycle(adjacency: np.ndarray, node_types: np.ndarray) -> bool:
    """Detect cycles in the undirected clone-only subgraph.

    We restrict the traversal to root/clone nodes (types ``0`` and ``1``) and
    treat edges of type ``1`` as undirected connections.  A depth-first search
    that revisits a node that is not the direct parent reveals a cycle.
    """

    clone_like = np.flatnonzero((node_types == 0) | (node_types == 1))
    if clone_like.size == 0:
        return False

    visited: set[int] = set()

    for start in clone_like:
        if start in visited:
            continue
        stack: List[Tuple[int, int]] = [(start, -1)]
        while stack:
            node, parent = stack.pop()
            if node in visited:
                # Encountering a previously visited node from a different
                # branch signals a cycle.
                if parent != -1:
                    return True
                continue
            visited.add(node)
            neighbours = _clone_neighbors(adjacency, node_types, node)
            for neighbour in neighbours:
                if neighbour == parent:
                    continue
                if neighbour in visited:
                    return True
                stack.append((neighbour, node))

    return False


def _validate_edge_types(adjacency: np.ndarray, node_types: np.ndarray) -> Tuple[bool, bool]:
    """Ensure clone/clone links use clone edges and clone/mutation links use mutation edges."""

    clone_edge_types_valid = True
    mutation_edge_types_valid = True

    node_count = adjacency.shape[0]
    for i in range(node_count):
        for j in range(i + 1, node_count):
            edge_type = adjacency[i, j]
            if edge_type == 0:
                continue

            node_i_type = node_types[i]
            node_j_type = node_types[j]

            if edge_type == 1:
                # Clone edges should only connect the root or clones to other clones.
                if not ((node_i_type in (0, 1)) and (node_j_type in (0, 1))):
                    clone_edge_types_valid = False
            elif edge_type == 2:
                # Mutation edges must bridge clone and mutation nodes.
                valid_pair = ((node_i_type == 1 and node_j_type == 2) or
                              (node_i_type == 2 and node_j_type == 1))
                if not valid_pair:
                    mutation_edge_types_valid = False

    return clone_edge_types_valid, mutation_edge_types_valid


def _check_root_degree(adjacency: np.ndarray, node_types: np.ndarray) -> bool:
    """Confirm the root has exactly one clone neighbour via clone edges."""

    root_indices = np.flatnonzero(node_types == 0)
    if root_indices.size != 1:
        return False

    root_idx = int(root_indices[0])
    neighbours = _clone_neighbors(adjacency, node_types, root_idx)

    # Only count neighbours that are real clone nodes (type ``1``).
    clone_neighbours = [idx for idx in neighbours if node_types[idx] == 1]
    return len(clone_neighbours) == 1 and len(neighbours) == 1


def compute_tree_metrics(tree_dict: Mapping[str, Any]) -> TreeMetrics:
    """Compute the metrics and validity flags for a single tree dictionary."""

    node_types, adjacency, _labels = _to_numpy(tree_dict)

    total_nodes = int(node_types.size)
    root_nodes = int(np.count_nonzero(node_types == 0))
    clone_nodes = int(np.count_nonzero(node_types == 1))
    mutation_nodes = int(np.count_nonzero(node_types == 2))

    total_edges, clone_edges, mutation_edges = _count_edges(adjacency)

    has_cycle = _has_clone_cycle(adjacency, node_types)
    root_degree_valid = _check_root_degree(adjacency, node_types)
    clone_edge_types_valid, mutation_edge_types_valid = _validate_edge_types(adjacency, node_types)

    all_rules_ok = (not has_cycle and root_degree_valid and
                    clone_edge_types_valid and mutation_edge_types_valid)

    validity = ValidityResult(
        is_valid=all_rules_ok,
        has_cycle=has_cycle,
        root_has_single_clone_neighbor=root_degree_valid,
        clone_edge_types_valid=clone_edge_types_valid,
        mutation_edge_types_valid=mutation_edge_types_valid,
    )

    return TreeMetrics(
        tree_id=str(tree_dict.get("tree_id", "unknown")),
        total_nodes=total_nodes,
        root_nodes=root_nodes,
        clone_nodes=clone_nodes,
        mutation_nodes=mutation_nodes,
        total_edges=total_edges,
        clone_edges=clone_edges,
        mutation_edges=mutation_edges,
        validity=validity,
    )



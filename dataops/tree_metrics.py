def aggregate_metrics(metrics: Sequence[TreeMetrics]) -> Dict[str, float]:
    """Return mean values for the requested metric fields."""

    if not metrics:
        return {
            "average_total_nodes": 0.0,
            "average_root_nodes": 0.0,
            "average_clone_nodes": 0.0,
            "average_mutation_nodes": 0.0,
            "average_total_edges": 0.0,
            "average_clone_edges": 0.0,
            "average_mutation_edges": 0.0,
        }

    def mean(values: Iterable[int]) -> float:
        arr = np.fromiter(values, dtype=float)
        return float(arr.mean()) if arr.size else 0.0

    return {
        "average_total_nodes": mean(metric.total_nodes for metric in metrics),
        "average_root_nodes": mean(metric.root_nodes for metric in metrics),
        "average_clone_nodes": mean(metric.clone_nodes for metric in metrics),
        "average_mutation_nodes": mean(metric.mutation_nodes for metric in metrics),
        "average_total_edges": mean(metric.total_edges for metric in metrics),
        "average_clone_edges": mean(metric.clone_edges for metric in metrics),
        "average_mutation_edges": mean(metric.mutation_edges for metric in metrics),
    }


def metric_series(metrics: Sequence[TreeMetrics]) -> Dict[str, List[int]]:
    """Expose raw metric lists so callers can build custom plots if desired."""

    return {
        "total_nodes": [metric.total_nodes for metric in metrics],
        "root_nodes": [metric.root_nodes for metric in metrics],
        "clone_nodes": [metric.clone_nodes for metric in metrics],
        "mutation_nodes": [metric.mutation_nodes for metric in metrics],
        "total_edges": [metric.total_edges for metric in metrics],
        "clone_edges": [metric.clone_edges for metric in metrics],
        "mutation_edges": [metric.mutation_edges for metric in metrics],
    }


def create_histograms(series: Mapping[str, Sequence[int]], bins: str | int = "auto") -> Dict[str, plt.Figure]:
    """Produce a single 2x3 subplot figure with distributions and mean lines.

    The figure contains:
    - Row 1: total_nodes, clone_nodes, mutation_nodes distributions
    - Row 2: total_edges, clone_edges, mutation_edges distributions
    Each subplot includes a horizontal line indicating the mean value.

    The caller takes ownership of the returned figure (e.g., display in a
    notebook or save to disk).  Using a helper keeps the plotting code in one
    place so that styling tweaks stay consistent.
    """

    # Create a single figure with 2x3 subplots
    fig, axes = plt.subplots(2, 3, figsize=(15, 10))

    # Row 1: Node distributions
    node_metrics = [
        ("total_nodes", 0, 0),    # Top-left
        ("clone_nodes", 0, 1),     # Top-middle
        ("mutation_nodes", 0, 2),  # Top-right
    ]

    # Row 2: Edge distributions
    edge_metrics = [
        ("total_edges", 1, 0),     # Bottom-left
        ("clone_edges", 1, 1),      # Bottom-middle
        ("mutation_edges", 1, 2),   # Bottom-right
    ]

    # Plot node distributions (row 1)
    for key, row, col in node_metrics:
        if key not in series:
            axes[row, col].axis("off")
            continue

        values = series[key]
        arr = np.asarray(list(values), dtype=float)
        mean_val = float(np.mean(arr))

        # Apply integer-aligned binning only for clone nodes
        if key == "clone_nodes":
            # For integer data, create bins centered on whole numbers
            # Bins edges are at 0.5, 1.5, 2.5, etc. so bars center on integers
            min_val = int(np.min(arr))
            max_val = int(np.max(arr)) + 1
            bin_edges = np.arange(min_val - 0.5, max_val + 1.5, 1)

            # Create histogram with integer-aligned bins
            axes[row, col].hist(arr, bins=bin_edges, edgecolor="black", align="mid")
            
            # Set integer tick marks on x-axis
            # Show all integers if range is small, otherwise show every 2-3 integers
            tick_range = max_val - min_val
            if tick_range <= 20:
                # Show every integer for small ranges
                axes[row, col].set_xticks(np.arange(min_val, max_val + 1))
            elif tick_range <= 40:
                # Show every 2 integers for medium ranges
                axes[row, col].set_xticks(np.arange(min_val, max_val + 1, 2))
            else:
                # Show every 5 integers for large ranges
                axes[row, col].set_xticks(np.arange(min_val, max_val + 1, 5))
        else:
            # Use default binning for other metrics
            axes[row, col].hist(arr, bins=bins, edgecolor="black")
        
        # Add vertical line at the mean value
        axes[row, col].axvline(mean_val, color="red", linestyle="--", linewidth=2)

        # Set labels and styling
        axes[row, col].set_title(f"Distribution of {key.replace('_', ' ')}")
        axes[row, col].set_xlabel(key.replace('_', ' '))
        axes[row, col].set_ylabel("count")
        axes[row, col].grid(True, linestyle=":", alpha=0.4)

    # Plot edge distributions (row 2)
    for key, row, col in edge_metrics:
        if key not in series:
            axes[row, col].axis("off")
            continue

        values = series[key]
        arr = np.asarray(list(values), dtype=float)
        mean_val = float(np.mean(arr))

        # Apply integer-aligned binning only for clone edges
        if key == "clone_edges":
            # For integer data, create bins centered on whole numbers
            # Bins edges are at 0.5, 1.5, 2.5, etc. so bars center on integers
            min_val = int(np.min(arr))
            max_val = int(np.max(arr)) + 1
            bin_edges = np.arange(min_val - 0.5, max_val + 1.5, 1)

            # Create histogram with integer-aligned bins
            axes[row, col].hist(arr, bins=bin_edges, edgecolor="black", align="mid")
            
            # Set integer tick marks on x-axis
            # Show all integers if range is small, otherwise show every 2-3 integers
            tick_range = max_val - min_val
            if tick_range <= 20:
                # Show every integer for small ranges
                axes[row, col].set_xticks(np.arange(min_val, max_val + 1))
            elif tick_range <= 40:
                # Show every 2 integers for medium ranges
                axes[row, col].set_xticks(np.arange(min_val, max_val + 1, 2))
            else:
                # Show every 5 integers for large ranges
                axes[row, col].set_xticks(np.arange(min_val, max_val + 1, 5))
        else:
            # Use default binning for other metrics
            axes[row, col].hist(arr, bins=bins, edgecolor="black")
        
        # Add vertical line at the mean value
        axes[row, col].axvline(mean_val, color="red", linestyle="--", linewidth=2)

        # Set labels and styling
        axes[row, col].set_title(f"Distribution of {key.replace('_', ' ')}")
        axes[row, col].set_xlabel(key.replace('_', ' '))
        axes[row, col].set_ylabel("count")
        axes[row, col].grid(True, linestyle=":", alpha=0.4)

    plt.tight_layout()  # Adjust spacing between subplots

    # Return dict with single figure for compatibility
    return {"all_metrics": fig}


def validity_summary(metrics: Sequence[TreeMetrics]) -> Dict[str, Any]:
    """Summarise validity outcomes, including the pass percentage."""

    if not metrics:
        return {
            "passed": 0,
            "failed": 0,
            "pass_percentage": 0.0,
        }

    passed = sum(1 for metric in metrics if metric.validity.is_valid)
    failed = len(metrics) - passed
    pass_percentage = (passed / len(metrics)) * 100.0
    return {
        "passed": passed,
        "failed": failed,
        "pass_percentage": pass_percentage,
    }


